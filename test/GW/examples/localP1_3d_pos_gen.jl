function local_CY_table(kMax, dMax, gen; factorAns::Bool=false)
  println("Genus $gen:")
  for k in 0:kMax
    a1 = -1+k
    a2 = -1-k
    gw = local_p1_invariants_3d(a1, a2, dMax, gen)
    print("k=$k")
    for x in gw
      if factorAns
        print(" & \\frac{$(factor(numerator(x)))}{$(factor(denominator(x)))}")
      else
        print(" & $x")
      end
    end
    print(" \\\\\n")
  end
end

