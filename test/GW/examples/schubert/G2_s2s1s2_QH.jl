# This file deals with the smooth Schubert variety in G/B in type G2, given by s2*s1*s2.
# In particular, we wish to calculate quantum products in the basis of Schubert classes.

R = root_system(:G, 2)
S = simple_roots(R)
GPS = generalized_gkm_schubert(R, S[1:0], "s2*s1*s2")
BO = get_bruhat_order_of_generalized_flag(R, S[1:0]);
G = GPS.self

SC = schubert_classes(GPS, BO)
QC = [QH_class(G, SC[i,:]) for i in 1:6]
QH_structure_constants_in_basis(G, SC; setPreferredBasis=true) # make sure the output is printed in the Schubert basis
set_attribute!(G, :QH_use_only_existing_structure_constants, true) # allow truncated output for quantum products

beta = curve_class(G, "s1", "id") # Chern number 0 generator
gamma = curve_class(G, "id", "s2") # Chern number 2 generator

for a in 0:2
	for b in 0:3
    println("Calculating curve class $a*beta + $b*gamma = $(a*beta+b*gamma)")
    QH_structure_constants(G, a*beta + b*gamma)
  end
end

for i in 1:6
  for j in i:6
    continue
    println("QC[$i] * QC[$j]:")
    println(QC[i] * QC[j])
  end
end

