

function get_convexity_example()
    G = empty_gkm_graph(16, 3, ["$i" for i in 1:16])
    x, y, z = gens(G.M)
    
    # 2D non-convex subgraph.
    add_edge!(G, 1, 2, x)
    add_edge!(G, 2, 3, y)
    add_edge!(G, 3, 4, -x)
    add_edge!(G, 4, 5, -y)
    add_edge!(G, 5, 6, x)
    add_edge!(G, 6, 7, y)
    add_edge!(G, 7, 8, -x)
    add_edge!(G, 8, 1, -y)
    
    # upper square
    add_edge!(G, 9, 11, x)
    add_edge!(G, 11, 13, y)
    add_edge!(G, 13, 15, -x)
    add_edge!(G, 15, 9, -y)
    
    # lower square
    add_edge!(G, 10, 12, x)
    add_edge!(G, 12, 14, y)
    add_edge!(G, 14, 16, -x)
    add_edge!(G, 16, 10, -y)
    
    # add fibers
    add_edge!(G, 1, 9, x+y+z)
    add_edge!(G, 9, 5, x+y-z)
    add_edge!(G, 1, 10, x+y-z)
    add_edge!(G, 10, 5, x+y+z)
    
    add_edge!(G, 2, 11, -x+y+z)
    add_edge!(G, 11, 6, -x+y-z)
    add_edge!(G, 2, 12, -x+y-z)
    add_edge!(G, 12, 6, -x+y+z)
    
    add_edge!(G, 3, 13, -x+y+z)
    add_edge!(G, 13, 7, -x+y-z)
    add_edge!(G, 3, 14, -x+y-z)
    add_edge!(G, 14, 7, -x+y+z)
    
    add_edge!(G, 4, 15, -x+y+z)
    add_edge!(G, 15, 8, -x+y-z)
    add_edge!(G, 4, 16, -x+y-z)
    add_edge!(G, 16, 8, -x+y+z)

    return G
end

